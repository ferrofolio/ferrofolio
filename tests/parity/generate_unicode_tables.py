"""Generate the Unicode tables the Rust port uses to behave like Python.

    python tests/parity/generate_unicode_tables.py --write
    python tests/parity/generate_unicode_tables.py --check

The tables follow the Unicode database of the running Python, so run this with the
Python version the backend uses (3.14, Unicode 16.0.0). --check exits with status 1
when a file does not match what this Python produces.
"""

import argparse
import sys
import unicodedata
from pathlib import Path

from ci_python import require_ci_python

ROOT = Path(__file__).resolve().parents[2]
BEGIN = "// BEGIN GENERATED by tests/parity/generate_unicode_tables.py\n"
END = "\n// END GENERATED"


def digit_zeros():
    zeros = [
        code
        for code in range(sys.maxunicode + 1)
        if unicodedata.category(chr(code)) == "Nd"
        and unicodedata.decimal(chr(code)) == 0
    ]
    for zero in zeros:
        for value in range(10):
            character = chr(zero + value)
            if (
                unicodedata.category(character) != "Nd"
                or unicodedata.decimal(character) != value
            ):
                raise SystemExit(f"digits after U+{zero:04X} are not a block of ten")
    total = sum(
        1
        for code in range(sys.maxunicode + 1)
        if unicodedata.category(chr(code)) == "Nd"
    )
    if total != 10 * len(zeros):
        raise SystemExit("not every decimal digit belongs to a block of ten")
    return zeros


def non_printable_ranges():
    ranges = []
    start = None
    for code in range(sys.maxunicode + 2):
        printable = code > sys.maxunicode or chr(code).isprintable()
        if not printable and start is None:
            start = code
        if printable and start is not None:
            ranges.append((start, code - 1))
            start = None
    return ranges


def digits_table():
    zeros = digit_zeros()
    items = [f"0x{zero:05X}," for zero in zeros]
    lines = ["    " + " ".join(items[i : i + 10]) for i in range(0, len(items), 10)]
    return (
        "/// First code point of every block of ten decimal digits (Unicode category Nd) in\n"
        f"/// Unicode {unicodedata.unidata_version}, the version of Python 3.14. Every block "
        "holds the digits 0 to 9 in\n"
        "/// order, so a digit's value is its distance from the start of its block. Generated\n"
        f"/// with `unicodedata`; the blocks cover all {10 * len(zeros)} Nd characters.\n"
        f"const DIGIT_ZEROS: [u32; {len(zeros)}] = [\n" + "\n".join(lines) + "\n];"
    )


def printable_table():
    ranges = non_printable_ranges()
    lines = [f"    (0x{first:05X}, 0x{last:05X})," for first, last in ranges]
    return (
        "/// Inclusive ranges of the code points Python 3.14 "
        f"(Unicode {unicodedata.unidata_version}) does\n"
        "/// not print in `repr()`: control, format, surrogate, private-use and unassigned\n"
        "/// characters and all separators except the ASCII space. Generated with\n"
        "/// `str.isprintable`.\n"
        f"const NON_PRINTABLE: [(u32, u32); {len(ranges)}] = [\n"
        + "\n".join(lines)
        + "\n];"
    )


TABLES = {
    ROOT / "crates/core-domain/src/unicode_digits.rs": digits_table,
    ROOT / "crates/server/src/python_printable.rs": printable_table,
}


def render(path, table):
    text = path.read_text(encoding="utf-8")
    start = text.index(BEGIN) + len(BEGIN)
    end = text.index(END, start)
    return text[:start] + table() + text[end:]


UNICODE_VERSION = "16.0.0"


def main():
    require_ci_python()
    if unicodedata.unidata_version != UNICODE_VERSION:
        print(
            f"needs the Unicode {UNICODE_VERSION} database of Python 3.14, this Python "
            f"has {unicodedata.unidata_version}",
            file=sys.stderr,
        )
        return 2
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="rewrite the tables")
    group.add_argument("--check", action="store_true", help="compare the tables")
    args = parser.parse_args()

    stale = []
    for path, table in TABLES.items():
        rendered = render(path, table)
        if args.write:
            path.write_text(rendered, encoding="utf-8")
        elif path.read_text(encoding="utf-8") != rendered:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print(
            f"out of date, regenerate with --write: {', '.join(stale)}", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
